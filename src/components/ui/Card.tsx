import React from "react";
import { cn } from "@/lib/utils";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverEffect?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverEffect = false, children, ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={cn(
          "bg-white rounded-[1.75rem] sm:rounded-3xl border border-slate-200/80 shadow-[0_1px_3px_rgba(0,0,0,0.03),0_8px_24px_-4px_rgba(15,23,42,0.06)] overflow-hidden transition-all duration-300",
          hoverEffect && "hover:shadow-[0_4px_6px_rgba(0,0,0,0.04),0_12px_32px_-4px_rgba(15,23,42,0.1)] hover:-translate-y-1",
          className
        )}
        {...props}
      >
        {children}
      </div>
    );
  }
);
Card.displayName = "Card";

export const CardHeader = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div ref={ref} className={cn("p-6 pb-3 space-y-1.5", className)} {...props} />
  )
);
CardHeader.displayName = "CardHeader";

